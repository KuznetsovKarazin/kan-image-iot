"""Build a factual report and scientific figures from recorded results."""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE=Path(__file__).resolve().parent
MODELS=["small_24_16","full_24_16","small_32_24_16"]
NAMES={"small_24_16":"24–16–2, α=0.25", "full_24_16":"24–16–2, α=1.0",
       "small_32_24_16":"32–24–16–2, α=0.25"}
POINTS=[16,32,64,128,256]


def main():
    s=json.loads((HERE/"results/synthetic/metrics.json").read_text())
    r=json.loads((HERE/"results/images/metrics.json").read_text())
    meta=json.loads((HERE/"results/images/run.json").read_text())
    native=json.loads((HERE/"results/images/native_checks.json").read_text())
    posthoc=json.loads((HERE/"results/anchored_control/metrics.json").read_text())
    verification=json.loads((HERE/"results/verification.json").read_text())
    def row(m,v,g=256):
        return next(x for x in r if x["model"]==m and x["variant"]==v and x["points"]==g)
    text=["# Conversion-fidelity pilot: measured results", "",
        "The predeclared synthetic gate passed on all three saved checkpoints and all three input seeds. "
        "The image results below are an exploratory paired conversion audit. They do not reproduce the "
        "old Micro tables and do not establish an MCU speed or energy advantage.", "",
        "![Conversion fidelity and classification accuracy](results/fidelity_summary.png)", "",
        "Figure: top panels show median RMSE and the min–max range over three synthetic input "
        "seeds (the bands are not confidence intervals). Bottom panels show accuracy on the "
        "same 1,024 images for each checkpoint. Post hoc anchored controls are tabulated separately.", "",
        "## Image result: 1,024 evaluation images", "",
        "Calibration uses 256 separate images; evaluation is balanced (512 per class). "
        "All variants receive the same FP32 MobileNet/projector features. The primary resolution is 256 points per edge.", "",
        "| Model | Original FP32 accuracy | Old whole LUT, 16 | Old whole LUT, 256 | Edge FP32, 256 | Edge INT8 storage, 256 |",
        "|---|---:|---:|---:|---:|---:|"]
    for m in MODELS:
        vals=[row(m,"reference",0),row(m,"legacy_whole",16),row(m,"legacy_whole"),row(m,"edge_fp32"),row(m,"edge_int8_table")]
        text.append("| "+NAMES[m]+" | "+" | ".join(f"{x['accuracy_pct']:.3f}%" for x in vals)+" |")
    text += ["", "Accuracy is agreement with labels; fidelity is agreement with the original FP32 model. "
             "A small gain in accuracy after quantization can coexist with changed predictions and is not evidence of exact conversion.", "",
             "| Model | Edge FP32 disagreement | Edge INT8 disagreement | Edge INT8 Δ accuracy (pp), paired 95% CI | Edge INT8 stored bytes |",
             "|---|---:|---:|---|---:|"]
    for m in MODELS:
        f,q=row(m,"edge_fp32"),row(m,"edge_int8_table")
        ci=q["delta_paired_stratified_bootstrap95_pp"]
        text.append(f"| {NAMES[m]} | {f['disagreement_count']}/1024 ({f['disagreement_pct']:.3f}%) | "
          f"{q['disagreement_count']}/1024 ({q['disagreement_pct']:.3f}%) | "
          f"{q['accuracy_delta_pp']:+.3f} [{ci[0]:+.3f}, {ci[1]:+.3f}] | {q['stored_bytes']:,} |")
    text += ["", "INT8 describes stored table entries only. Interpolation, scaling and activations remain FP32. "
        "Reported stored bytes include table values, per-edge scales, calibration bounds and affine parameters; "
        "they exclude CNN weights, executable code and runtime memory.", "",
        "## Diagnostic controls", "",
        "| Model | Exact axis mean accuracy | Exact anchored additive control | Old LUT with calibrated domain, 256 | Existing layerwise converter, 32 |",
        "|---|---:|---:|---:|---:|"]
    for m in MODELS:
        vals=[row(m,"exact_axis_mean",0),row(m,"exact_anchored_additive_control",0),
              row(m,"legacy_calibrated_domain"),row(m,"legacy_layerwise",32)]
        text.append("| "+NAMES[m]+" | "+" | ".join(f"{x['accuracy_pct']:.3f}%" for x in vals)+" |")
    text += ["", "The original whole-network transformation tends to g(x)=mean_i f(x_i e_i), "
        "not f(x). The exact-axis control removes table discretization. The anchored control "
        "f(0)+sum_i[f(x_i e_i)-f(0)] removes the mean/offset error but still cannot generally "
        "represent interactions generated by composed nonlinear layers. The old layerwise class "
        "sums whole-layer axis sections, repeating nonzero edge intercepts; the independent "
        "constant-edge test proves this even without discretization error.", "",
        "### Post hoc cheaper-control check", "",
        "The exact anchored control exposed a useful alternative. After the primary run, we "
        "specified FOLLOWUP_PROTOCOL.md and evaluated 30 additional derived variants, without "
        "fitting to labels. The calibrated whole-head LUT can be re-centered as "
        "d·LUT(x)−(d−1)·f(0). Its class predictions can be close to the reference while its "
        "probabilities remain different. Probability RMSE below is against the original model, "
        "not a measure of calibration to ground truth.", "",
        "| Model | Anchored whole LUT, 32: disagreement | Anchored probability RMSE | Edge INT8, 32: disagreement | Edge INT8 probability RMSE |",
        "|---|---:|---:|---:|---:|"]
    for m in MODELS:
        a=next(x for x in posthoc if x['model']==m and x['variant']=='anchored_legacy_calibrated_domain' and x['points']==32)
        q=next(x for x in posthoc if x['model']==m and x['variant']=='edge_int8_table' and x['points']==32)
        text.append(f"| {NAMES[m]} | {a['disagreement_count']}/1024 | {a['person_probability_rmse']:.6f} | "
                    f"{q['disagreement_count']}/1024 | {q['person_probability_rmse']:.6f} |")
    text += ["", "This control prevents a claim that full edge compilation is always necessary for "
        "classification accuracy. The defensible distinction is numerical/probability fidelity, "
        "memory cost and behavior beyond this particular operating threshold. All resolutions "
        "of this exploratory control are retained in results/anchored_control/metrics.json.", "",
        "| Model | Features outside old [-2,2] | Images with any such feature | Edge FP32 saturation per layer, 256 |",
        "|---|---:|---:|---|"]
    for m in MODELS:
        cov=meta["models"][m]["feature_coverage"]
        sat=row(m,"edge_fp32")["saturation_by_layer"]
        text.append(f"| {NAMES[m]} | {cov['features_outside_legacy_domain_pct']:.3f}% | "
          f"{cov['images_with_feature_outside_legacy_domain_pct']:.3f}% | "+", ".join(f"{100*v:.3f}%" for v in sat)+" |")
    text += ["", "Saturation is counted on the converted trajectory at each layer. A lower saturation "
        "rate does not itself guarantee a smaller prediction error. Results for all five resolutions "
        "and the separate out-of-range synthetic stress test are retained.", "",
        "## Synthetic gate", "",
        "There are 297 recorded comparisons: three checkpoints, input seeds 42/43/44, five table "
        "resolutions, in-range and stress inputs, and diagnostic controls. Each seed uses 4,096 "
        "calibration, 4,096 evaluation and 4,096 stress vectors. These seeds do not represent "
        "independent training runs. Class disagreement on synthetic features is not image accuracy.", "",
        "| Model | RMSE reduction, old 256 / edge FP32 256, across three seeds | Edge FP32 disagreements per 4,096 |",
        "|---|---|---|"]
    for gate in verification["synthetic_gate"]:
        m=gate["model"]
        counts=[x["disagreement_count"] for x in s if x["model"]==m and x["variant"]=="edge_fp32" and x["points"]==256 and x["dataset"]=="in_range"]
        text.append(f"| {NAMES[m]} | "+", ".join(f"{x:.1f}×" for x in gate["rmse_reduction_ratios"])+" | "+", ".join(map(str,counts))+" |")
    text += ["", "The separate [0,4] stress inputs exceed the calibration interval. The edge LUT "
        "saturates there and is not globally equivalent to the original network:", "",
        "| Model | Edge FP32 256: stress disagreement range across seeds | First-layer saturated values |",
        "|---|---:|---:|"]
    for m in MODELS:
        values=[x for x in s if x['model']==m and x['variant']=='edge_fp32' and x['points']==256 and x['dataset']=='stress']
        ds=[x['disagreement_pct'] for x in values]
        sat=[x['saturation_by_layer'][0]*100 for x in values]
        text.append(f"| {NAMES[m]} | {min(ds):.2f}–{max(ds):.2f}% | {min(sat):.2f}–{max(sat):.2f}% |")
    text += ["", "## Native C check", "",
        "The generator emitted C99 with actual int8_t tables and FP32 arithmetic. Each 256-point "
        "INT8-storage image model was compiled with warnings treated as errors, then tested on "
        "the same 1,024 feature vectors. Acceptance required allclose(atol=2e-5, rtol=2e-5) and "
        "zero changed class decisions relative to the Python table evaluator.", "",
        "| Model | Maximum C/Python logit difference | Changed decisions | Explicit two activation buffers |",
        "|---|---:|---:|---:|"]
    for m in MODELS:
        x=native[m]
        text.append(f"| {NAMES[m]} | {x['max_abs_error_vs_python_lut']:.3g} | {x['decision_disagreements_vs_python_lut']} | {x['explicit_activation_buffers_bytes']} B |")
    text += ["", "The two arrays are not a measurement of total stack or MCU SRAM. CPU head-only "
        "timings are archived in native_checks.json, but no speedup claim is made from them.", "",
        "## Validation and limitations", "",
        f"- Ten mathematical/implementation tests pass. Independent saved-array verification recalculates "
        f"{verification['synthetic_rows_recalculated']} synthetic and {verification['image_rows_recalculated']} image rows, "
        "including paired error counts and Wilson intervals; 30 post hoc derived rows are also recalculated.",
        "- All three full checkpoints load strictly. Original weights and conversion source are unchanged. "
        "No retraining or selection by pilot accuracy was performed.",
        "- The historical 16–4–2 checkpoints and exact 6,000-image manifests are absent. "
        "The selected models are 24–16–2 and 32–24–16–2.",
        "- Evaluation IDs are in the repository minival list and disjoint from this pilot's calibration IDs. "
        "Their possible use for historical checkpoint selection is unknown. Bootstrap intervals "
        "measure image sampling only, not training uncertainty or generalization to a new deployment.",
        "- A [0,0] paired-bootstrap interval when all observed paired differences are zero is a "
        "degenerate empirical bootstrap result, not proof of zero population error or equivalence. "
        "Likewise, zero class changes in 1,024 images is an observed count, not a universal guarantee.",
        "- No physical MCU, fully INT8 activation path, TFLite graph, energy measurement or matched "
        "MLP comparison was run. Symbolic edges, multiplication nodes and remapped inputs are "
        "explicitly rejected by this pilot implementation.", "",
        "## Decision for the article", "",
        "Proceed to a bounded hardware validation, subject to obtaining the exact old checkpoints "
        "and locked data. The defensible candidate result is that a small executable conversion "
        "can silently change the learned function, and that separating structural approximation, "
        "clipping, table precision and runtime arithmetic exposes the cause. Per-edge LUT "
        "compilation itself is prior work. See PRIOR_WORK.md for six related publications and "
        "the proposed boundary of the revised article.", "",
        "Next experiment: carry identical model parameters and golden feature vectors to ESP32-S3; "
        "compare original-converter and layer-preserving paths at common memory budgets; measure "
        "head-only and full CNN+head latency, Flash, peak SRAM/PSRAM and energy, with a matched "
        "MLP. Use the exact old 16–4–2 model as the bridge to the rejection, plus these two topologies.", "",
        "## Complete image sweep", "",
        "| Model | Points | Old accuracy | Edge FP32 accuracy | Edge INT8 accuracy | FP32 disagreement | INT8 disagreement | INT8 bytes |",
        "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for m in MODELS:
        for g in POINTS:
            a,f,q=row(m,"legacy_whole",g),row(m,"edge_fp32",g),row(m,"edge_int8_table",g)
            text.append(f"| {NAMES[m]} | {g} | {a['accuracy_pct']:.3f}% | {f['accuracy_pct']:.3f}% | {q['accuracy_pct']:.3f}% | "
              f"{f['disagreement_pct']:.3f}% | {q['disagreement_pct']:.3f}% | {q['stored_bytes']:,} |")
    (HERE/"REPORT.md").write_text("\n".join(text)+"\n")

    fig,axes=plt.subplots(2,3,figsize=(12,7),layout="constrained")
    styles=[("legacy_whole","Whole-head LUT","#b45438"),("edge_fp32","Edge FP32","#176c91"),
            ("edge_int8_table","Edge INT8 storage","#597d3a")]
    for j,m in enumerate(MODELS):
        for variant,label,color in styles:
            values=np.array([[x["rmse"] for x in s if x["model"]==m and x["variant"]==variant and
                              x["points"]==g and x["dataset"]=="in_range"] for g in POINTS])
            axes[0,j].plot(POINTS,np.median(values,axis=1),"o-",label=label,color=color,ms=4)
            axes[0,j].fill_between(POINTS,values.min(1),values.max(1),color=color,alpha=.12)
            axes[1,j].plot(POINTS,[row(m,variant,g)["accuracy_pct"] for g in POINTS],"o-",color=color,ms=4)
        axes[0,j].set_title(NAMES[m],fontsize=11)
        axes[0,j].set_yscale("log")
        axes[1,j].axhline(row(m,"reference",0)["accuracy_pct"],color="black",ls="--",lw=1,label="Original FP32")
        for ax in axes[:,j]:
            ax.set_xscale("log",base=2)
            ax.set_xticks(POINTS,labels=POINTS)
            ax.grid(alpha=.2)
            ax.set_xlabel("LUT points")
        axes[0,j].set_ylabel("Logit RMSE (synthetic)")
        axes[1,j].set_ylabel("Accuracy, % (1,024 COCO images)")
        axes[1,j].set_ylim(min(row(m,"legacy_whole",g)["accuracy_pct"] for g in POINTS)-3,
                           max(row(m,"reference",0)["accuracy_pct"],max(row(m,"edge_int8_table",g)["accuracy_pct"] for g in POINTS))+3)
    axes[0,0].legend(fontsize=8)
    axes[1,0].legend(fontsize=8)
    fig.suptitle("Conversion fidelity: structural approximation versus edge-table precision",fontsize=13)
    fig.savefig(HERE/"results/fidelity_summary.png",dpi=180)
    fig.savefig(HERE/"results/fidelity_summary.pdf")
    plt.close(fig)
    print("REPORT.md and scientific figures written")


if __name__=="__main__":
    main()
